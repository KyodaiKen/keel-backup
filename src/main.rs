//! keel — profile-driven, distribution-agnostic system backups.
//!
//! Commands:
//!   keel                 TUI (capabilities, plan, profile, live log)
//!   keel doctor          what this system can back up — and why the rest is hidden
//!   keel suggest         print a starting profile YAML for this host
//!   keel plan            show the backup plan for the profile (no writes)
//!   keel run             run the backup (needs root; sudo keel run)
//!
//! No machine-specific facts live in this binary: paths, UUIDs, users,
//! services all come from the profile file (and runtime detection).

mod detect;
mod engine;
mod manifest;
mod plan;
mod profile;
mod tui;
mod borg;

use std::io::Write as _;
use std::sync::{Arc, Mutex};
use std::time::Duration;

use anyhow::{bail, Result};
use clap::{Parser, Subcommand};
use indicatif::{MultiProgress, ProgressBar, ProgressStyle};

use plan::{EventArc, RunEvent};

#[derive(Parser)]
#[command(
    name = "keel",
    version,
    about = "Profile-driven, distro-agnostic, bare-metal-capable system backups"
)]
struct Cli {
    /// Profile file path, or a name (looked up under ~/.config/keel/profiles/).
    #[arg(long, global = true, value_name = "PROFILE")]
    profile: Option<String>,

    #[command(subcommand)]
    cmd: Option<Cmd>,
}

#[derive(Subcommand)]
enum Cmd {
    /// Show detected capabilities: what could back up here, and why the rest is hidden
    Doctor,
    /// Print a starting profile YAML for this host (fill in the destination)
    Suggest,
    /// Show the backup plan for the profile (no writes)
    Plan,
    /// Run the backup (sudo keel run)
    Run {
        /// Verify destination, plan and permissions — but write nothing
        #[arg(long)]
        dry_run: bool,
        /// Skip the confirmation prompt
        #[arg(short = 'y', long)]
        yes: bool,
    },
    /// Interactive TUI
    Tui,
}

fn main() -> Result<()> {
    let cli = Cli::parse();
    match cli.cmd {
        None | Some(Cmd::Tui) => tui::run_app(cli.profile),
        Some(Cmd::Doctor) => cmd_doctor(),
        Some(Cmd::Suggest) => cmd_suggest(),
        Some(Cmd::Plan) => cmd_plan(cli.profile.as_deref()),
        Some(Cmd::Run { dry_run, yes }) => cmd_run(cli.profile.as_deref(), dry_run, yes),
    }
}

fn cmd_doctor() -> Result<()> {
    let caps = detect::registry();
    println!("keel doctor — capabilities on this system\n");
    for c in &caps {
        let mark = if c.applicable { "✓" } else { "✗" };
        let state = if c.applicable {
            if c.implemented { "ready (Phase 0)" } else { "detected, engine lands Phase 1+" }
        } else {
            "hidden"
        };
        println!("{mark} {:<14} {}", c.title, state);
        println!("    why: {}", c.reason);
        for e in &c.evidence {
            println!("    · {e}");
        }
    }
    println!("\nTip: the TUI (bare `keel`) shows only the applicable entries in the dropdown;\npress `i` there (or see above) for why the rest are hidden.");
    Ok(())
}

fn cmd_suggest() -> Result<()> {
    let host = detect::hostname();
    let date = engine::date_utc(
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_secs() as i64)
            .unwrap_or(0),
    );
    let root_fs = detect::fs_type(std::path::Path::new("/"));
    let subs = detect::find_nested_subvolumes(&["/"]);

    let mut srcs = String::new();
    if matches!(root_fs.as_deref(), Some("btrfs")) {
        srcs.push_str("  - path: /\n    category: os\n    name: rootfs\n");
        for s in &subs {
            let name = s.trim_start_matches('/').replace('/', "_");
            let cat = if s == "/home" { "home" } else { "extra" };
            srcs.push_str(&format!("  - path: {s}\n    category: {cat}\n    name: {name}\n"));
        }
    } else {
        srcs.push_str("  # No btrfs subvolumes detected — non-btrfs trees are backed up with\n  # methods: [tar] (whole-tree tar+zstd) and/or [borg].\n  # e.g.  - path: /boot\n  #        category: boot\n  #        methods: [tar]\n");
    }

    let yaml = format!(
        r#"# keel profile — generated by `keel suggest` on {host} ({date}).
# Nothing here is personal to a machine: adjust paths/UUIDs to taste.
# Secrets (e.g. borg passphrases) go into the env_file, NEVER into this file.

name: {host}
description: daily system backup

# Locked-away file with KEY=VALUE lines, e.g. BORG_PASSPHRASE=... (chmod 600)
# env_file: ~/secrets/keel.env

destination:
  # Tried in order until one mounts and passes the write test.
  #   kind: uuid   →  - kind: uuid
  #                  uuid: "1234-abcd-..."
  #   kind: path   →  an already-mounted directory (used as-is)
  #   kind: device →  - kind: device
  #                   device: /dev/sdX
  #   kind: label  →  - kind: label
  #                  label: BACKUP
  candidates: []
  mount_point: /mnt/backup
  backups_dir: backups
  min_free: 50G

sources:
  # Per-source extras (all optional):
  #   name: home                  # manifest label (defaults to the path name)
  #   category: home              # day-dir subdirectory (os/home/boot/…)
  #   methods: [btrfs, borg, tar, squashfs]  # default: btrfs on subvolumes, tar elsewhere
  #   excludes: ["ollama-models/blobs"]      # tar globs / borg patterns; squashfs simple names expand per depth; btrfs streams are whole-subvolume
  # Tree extras beyond that: `path` (required), `name`, `category`.
  # Non-tree sources (kind:):  pg_dump {{database, user, host, port, run_as}}
  #                             podman_save {{images, commit {{container, tag}}, run_as}}
  #                             systemd_state {{}}
{srcs}
engines:
  zstd_level: 6
  zstd_threads: null   # null = auto

# methods:      # method settings (sources opt in via `methods: [btrfs, borg, tar, squashfs]`)
#   borg:
#     repo: /mnt/backup/borg-backups        # shared repo on the backup drive
#     passphrase_file: ~/secrets/borg.bp    # 0400, one line; opens pre-existing repos
#     compression: zstd,6
#     keep_daily: 2
#     keep_weekly: 4
#     keep_monthly: 12

retention:
  keep: 4              # keep the newest 4 day directories for this host
"#
    );
    print!("{yaml}");
    if matches!(root_fs.as_deref(), Some("btrfs")) {
        eprintln!("\n# detected btrfs on / — sources pre-filled ({subs} nested subvolume(s))", subs = subs.len());
    } else {
        eprintln!("\n# no btrfs detected on / ({root_fs:?}) — use methods: [tar] for those trees");
    }
    Ok(())
}

fn cmd_plan(profile_ref: Option<&str>) -> Result<()> {
    let (pp, prof) = profile::load(profile_ref)?;
    let p = plan::build_plan(&pp, &prof)?;
    println!("profile    : {} ({})", p.profile_name, pp.display());
    println!("destination: {}", p.destination);
    println!("day dir    : {}", p.day_dir.display());
    println!();
    for it in &p.items {
        for m in &it.methods {
            match m.kind {
                plan::MethodKind::Btrfs => println!("  {}/{}  ←  {}  [btrfs-send]", it.category, it.name, it.source.as_str()),
                plan::MethodKind::Tar => println!("  {}/{}  ←  {}  [tar+zstd]", it.category, it.name, it.source.as_str()),
                plan::MethodKind::Borg => {
                    let repo = prof.methods.borg.as_ref()
                        .map(|b| b.repo.display().to_string())
                        .unwrap_or_else(|| "<repo>".into());
                    println!("  {}  ←  {}  [borg → {}::{}]", it.name, it.source.as_str(), repo, m.artifact);
                }
                plan::MethodKind::Squashfs => println!("  {}  ←  {}  [squashfs]", it.name, it.source.as_str()),
                plan::MethodKind::PgDump => println!("  {}  ←  {}  [pg-dump]", it.name, it.source.as_str()),
                plan::MethodKind::PodmanSave => println!("  {}  ←  {}  [podman-save]", it.name, it.source.as_str()),
                plan::MethodKind::SystemdState => println!("  {}  ←  {}  [systemd-state]", it.name, it.source.as_str()),
            }
        }
    }
    println!("\nRun it with: sudo keel run");
    Ok(())
}

fn cmd_run(profile_ref: Option<&str>, dry_run: bool, yes: bool) -> Result<()> {
    let (pp, prof) = profile::load(profile_ref)?;
    let p = plan::build_plan(&pp, &prof)?;

    if !dry_run {
        println!(
            "keel will back up:\n  {} source(s) → {}{}",
            p.items.len(),
            p.day_dir.display(),
            if prof.retention.keep.is_some() {
                format!("\n  retention: keep {}", prof.retention.keep.unwrap())
            } else {
                "".into()
            }
        );
        if !yes {
            print!("Proceed? [y/N] ");
            std::io::stdout().flush().ok();
            let mut line = String::new();
            std::io::stdin().read_line(&mut line)?;
            if !line.trim().eq_ignore_ascii_case("y") && !line.trim().eq_ignore_ascii_case("yes") {
                bail!("aborted by user");
            }
        }
    }

    // One progress counter per source (btrfs send has no total → count-up).
    let mp = MultiProgress::new();
    let bars: Vec<(usize, ProgressBar)> = if dry_run {
        Vec::new()
    } else {
        p.items
            .iter()
            .map(|it| {
                let b = mp.add(ProgressBar::new(u64::MAX));
                b.set_style(
                    ProgressStyle::with_template(
                        "{spinner} {msg}  |  {bytes} raw  →  {prefix}"
                    )
                    .unwrap()
                    .tick_chars("⠋⠙⠹⠸⠼⠴⠦⠧⠇⠏"),
                );
                (it.idx, b)
            })
            .collect()
    };
    let bars2: Vec<(usize, ProgressBar)> = bars.clone();

    let sink: EventArc = Arc::new(Mutex::new(move |e: &RunEvent| {
        match e {
            RunEvent::Note(s) => println!("   · {s}"),
            RunEvent::Destination(s) => println!("   ▸ {s}"),
            RunEvent::DayDir(s) => println!("   ▸ day dir: {s}"),
            RunEvent::SourceStart { idx, label, engine, out_rel } => {
                if let Some((_, b)) = bars2.iter().find(|(i, _)| i == idx) {
                    b.enable_steady_tick(Duration::from_millis(120));
                    b.set_message(format!("{label} → {out_rel} ({engine})"));
                    b.set_prefix(String::new());
                }
            }
            RunEvent::Progress { idx, raw, written } => {
                if let Some((_, b)) = bars2.iter().find(|(i, _)| i == idx) {
                    b.set_position(*raw);
                    b.set_prefix(format!("{}", engine::human(*written)));
                }
            }
            RunEvent::SourceOk { idx, engine, note } => {
                if let Some((_, b)) = bars2.iter().find(|(i, _)| i == idx) {
                    b.finish_and_clear();
                    println!("   ✔ done [{engine}]: {note}");
                }
            }
            RunEvent::SourceFail { idx, err } => {
                if let Some((_, b)) = bars2.iter().find(|(i, _)| i == idx) {
                    b.finish_and_clear();
                    eprintln!("   ✘ failed: {err}");
                }
            }
            RunEvent::Manifest(s) => println!("   ▸ manifest: {s}"),
            RunEvent::Retained(s) => println!("   ▸ {s}"),
            RunEvent::Done => println!("   ✔ run complete"),
        }
    }));

    let res = plan::run(&p, &prof, &sink, dry_run);
    mp.clear().ok();
    res
}

